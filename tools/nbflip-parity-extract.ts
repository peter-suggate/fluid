/** Surface tension's (lane F, 2026-11-17): the old capillarity as it resolves for water-box-dam-break (sigma 0.072,
 * the uncached evaluator: umForceCached and umCachedGeometry off), into parity/uniform-tension.wgsl (--set=tension). */
export const TENSION_FUNCTIONS: Readonly<Record<string, readonly string[]>> = {
  "Uniform_mixed_forces.wgsl": [
    "umOrigin", "umFaceCenter", "umOwnerClosed", "umCellPhi", "umOccupancy", "umNormalRaw", "umNormal", "umCurvature", "umForceCurvature",
    "umPressure", "umPressureSlope", "umForceSample", "umReconstructSample", "umReconstructNeeds", "umReconstructPressureSlope",
    "umPressureFaceCorrection", "umReconstructedPressureGradient", "umCapillary",
  ],
};

export function wgslFunction(src: string, name: string): string | undefined {
  const m = new RegExp(`\\bfn ${name}\\s*\\(`).exec(src);
  if (!m) return undefined;
  let depth = 0;
  for (let j = src.indexOf("{", m.index); j < src.length; j++) {
    if (src[j] === "{") depth++;
    else if (src[j] === "}" && --depth === 0) return src.slice(m.index, j + 1);
  }
  return undefined;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const option = (key: string) => process.argv.slice(2).find(a => a.startsWith(`--${key}=`))?.slice(key.length + 3);
  const dir = resolve(option("capture") ?? assert.fail("--capture=DIR"));
  const commit = option("commit") ?? assert.fail("--commit=SHA");
  const tension = option("set") === "tension";
  const out = resolve(option("out") ?? `lib/methods/narrow-band/parity/${tension ? "uniform-tension" : "uniform-dam"}.wgsl`);
  const files = readdirSync(dir).filter(f => f.endsWith(".wgsl")).sort();
  const parts = [`// Old NB-FLIP engine functions, resolved for ${tension ? "water-box-dam-break" : "high-resolution-dam-break"} at ${commit}.`,
    "// Generated by tools/nbflip-parity-extract.ts; do not edit. Each function is introduced by a line \"// ==== name\"."];
  for (const [label, names] of Object.entries(tension ? TENSION_FUNCTIONS : PARITY_FUNCTIONS)) {
    const file = files.find(f => f.includes(label)) ?? assert.fail(`no captured module labelled ${label}`);
    const src = readFileSync(join(dir, file), "utf8");
    for (const name of names) {
      const text = wgslFunction(src, name) ?? assert.fail(`${name} not in ${file}`);
      parts.push(`// ==== ${name} (${file})`, text);
    }
  }
  writeFileSync(out, parts.join("\n") + "\n");
  console.log(`wrote ${out}`);
}
