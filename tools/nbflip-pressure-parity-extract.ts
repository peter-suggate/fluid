/** Extract the old NB-FLIP pressure arena's resolved WGSL functions that lane P's row formulas port
 * (lib/methods/narrow-band/pressure-rows.wgsl.ts) into parity/uniform-dam-pressure.wgsl, as
 * tools/nbflip-parity-extract.ts does for lane F's formulas (same capture, same format).
 *
 * node --import tsx tools/nbflip-pressure-parity-extract.ts --capture=DIR --commit=SHA [--out=FILE] */
import assert from "node:assert/strict";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { wgslFunction } from "./nbflip-parity-extract";

export const PRESSURE_PARITY_FUNCTIONS: Readonly<Record<string, readonly string[]>> = {
  "Uniform_pressure_arena_rows": ["bSign", "bTheta", "bPairTheta", "bFaceTheta", "bWet", "bLiquid", "bFaceKind", "pLift", "pRows"],
  "Uniform_pressure_arena_native": ["nTheta", "bSeamHead", "bResidualMagnitude", "pNative"],
  "Uniform_pressure_arena_init": ["pCorrectionFree"],
};

if (import.meta.url === `file://${process.argv[1]}`) {
  const option = (key: string) => process.argv.slice(2).find(a => a.startsWith(`--${key}=`))?.slice(key.length + 3);
  const dir = resolve(option("capture") ?? assert.fail("--capture=DIR"));
  const commit = option("commit") ?? assert.fail("--commit=SHA");
  const out = resolve(option("out") ?? "lib/methods/narrow-band/parity/uniform-dam-pressure.wgsl");
  const files = readdirSync(dir).filter(f => f.endsWith(".wgsl")).sort();
  const parts = [`// Old NB-FLIP pressure arena functions, resolved for high-resolution-dam-break at ${commit}.`,
    "// Generated by tools/nbflip-pressure-parity-extract.ts; do not edit. Each function is introduced by a line \"// ==== name\"."];
  for (const [label, names] of Object.entries(PRESSURE_PARITY_FUNCTIONS)) {
    const file = files.find(f => f.includes(label + ".wgsl")) ?? assert.fail(`no captured module labelled ${label}`);
    const src = readFileSync(join(dir, file), "utf8");
    for (const name of names) {
      const text = wgslFunction(src, name) ?? assert.fail(`${name} not in ${file}`);
      parts.push(`// ==== ${name} (${file})`, text);
    }
  }
  writeFileSync(out, parts.join("\n") + "\n");
  console.log(`wrote ${out}`);
}
